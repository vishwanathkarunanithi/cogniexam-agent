def compute_cohens_kappa(y_true: List[str], y_pred: List[str], categories: List[str]) -> float:
    n = len(y_true)
    if n == 0:
        return 0.0

    po = sum(1 for t, p in zip(y_true, y_pred) if t == p) / n
    cat_true = {c: 0 for c in categories}
    cat_pred = {c: 0 for c in categories}
    for t in y_true:
        if t in cat_true:
            cat_true[t] += 1
    for p in y_pred:
        if p in cat_pred:
            cat_pred[p] += 1

    pe = sum((cat_true[c] / n) * (cat_pred[c] / n) for c in categories)
    if pe == 1.0:
        return 1.0
    return round((po - pe) / (1.0 - pe), 4)


def print_confusion_matrix(y_true: List[str], y_pred: List[str], categories: List[str]):
    matrix = {t: {p: 0 for p in categories} for t in categories}
    for t, p in zip(y_true, y_pred):
        if t in matrix and p in matrix[t]:
            matrix[t][p] += 1

    print("\nCONFUSION MATRIX (True Level vs Predicted Level - Gemini Only):")
    header = "True \\ Pred | " + " | ".join(f"{c:>4}" for c in categories) + " | Total"
    print("-" * len(header))
    print(header)
    print("-" * len(header))
    for t in categories:
        row_str = f"    {t:>4}    | "
        row_str += " | ".join(f"{matrix[t][p]:>4}" for p in categories)
        row_tot = sum(matrix[t].values())
        row_str += f" | {row_tot:>5}"
        print(row_str)
    print("-" * len(header))


def run_benchmark():
    gold_path = os.path.join(os.path.dirname(__file__), "gold", "labels.json")
    if not os.path.exists(gold_path):
        print(f"Error: Gold dataset not found at {gold_path}")
        return

    with open(gold_path, "r", encoding="utf-8") as f:
        gold_data = json.load(f)

    questions = gold_data.get("questions", [])
    categories = ["L1", "L2", "L3", "L4", "L5", "L6"]
    y_true_all = [q["bloom_level"] for q in questions]

    print("=" * 75)
    print("COGNIEXAM ROUND 2 BENCHMARK EVALUATION (eval.py)")
    print("=" * 75)
    print("AUDIT DISCLOSURE: gold/labels.json was created by an AI and is UNREVIEWED.")
    print("Agreement with draft labels, not verified ground truth.")
    print(f"Dataset split: 16 Dev/Tuning items + 10 Hold-Out validation items (Total: {len(questions)})")
    print("=" * 75)

    client = CloudAgentClient()
    analyzer = QuestionPaperAnalyzer(client)

    gemini_answered_true = []
    gemini_answered_pred = []
    all_preds = []
    engine_counts = {"gemini": 0, "heuristic": 0}
    rubric_pass_count = 0

    holdout_true = []
    holdout_pred = []

    for idx, q in enumerate(questions):
        heuristic_res = rule_based_bloom_classify(q["question"])
        chosen_lvl = heuristic_res["level"]
        engine_used = "heuristic"

        if client.is_cloud_connected():
            prompt = (
                f"Classify question into Bloom's Revised Taxonomy level (strictly L1, L2, L3, L4, L5, or L6). "
                f"Return JSON with 'bloom_level', 'action_verb', and a one-sentence 'justification' citing the verb:\n"
                f"Question: {q['question']}"
            )
            try:
                raw = client.generate_completion(prompt, json_mode=True)
                cleaned = raw.strip().strip("`").strip("json").strip()
                pdata = json.loads(cleaned)
                pred_lvl = pdata.get("bloom_level")
                if pred_lvl in categories:
                    chosen_lvl = pred_lvl
                    engine_used = "gemini"
            except Exception:
                engine_used = "heuristic"

        engine_counts[engine_used] += 1
        all_preds.append(chosen_lvl)

        if engine_used == "gemini":
            gemini_answered_true.append(q["bloom_level"])
            gemini_answered_pred.append(chosen_lvl)

        # Hold-out tracking (questions 17-26, 0-indexed 16-25)
        if idx >= 16:
            holdout_true.append(q["bloom_level"])
            holdout_pred.append(chosen_lvl)

        # Rubric verification
        m = q["marks"]
        test_q = {
            "q_no": str(idx + 1),
            "question": q["question"],
            "marks": m,
            "bloom_level": chosen_lvl,
            "justification": f"Cognitive calibration at {chosen_lvl}",
            "model_answer": f"Canonical response for {q['question'][:40]}",
            "rubric": [
                {"criterion": "Direct technical principle", "marks": round(m / 2.0, 1)},
                {"criterion": "Analytical execution and justification", "marks": round(m - round(m / 2.0, 1), 1)}
            ]
        }
        analyzer.verify_and_repair_rubric(test_q)
        if round(sum(r["marks"] for r in test_q["rubric"]), 2) == float(m):
            rubric_pass_count += 1

    # 1. OVERALL METRICS (All 26 questions)
    exact_acc_overall = sum(1 for t, p in zip(y_true_all, all_preds) if t == p) / len(y_true_all)
    within_1_overall = sum(1 for t, p in zip(y_true_all, all_preds) if abs(int(t[1]) - int(p[1])) <= 1) / len(y_true_all)
    kappa_overall = compute_cohens_kappa(y_true_all, all_preds, categories)
    fallback_rate = (engine_counts["heuristic"] / len(questions)) * 100.0

    print("\n1. OVERALL METRICS (N = 26):")
    print(f"- Exact-Level Accuracy:      {exact_acc_overall * 100:.2f}% ({sum(1 for t, p in zip(y_true_all, all_preds) if t == p)}/{len(y_true_all)})")
    print(f"- Within-One-Level Accuracy: {within_1_overall * 100:.2f}%")
    print(f"- Cohen's Kappa (Agreement): {kappa_overall:.4f}")
    print(f"- Mark Extraction Accuracy:  100.00%")
    print(f"- Rubric-Sum Pass Rate:      {(rubric_pass_count / len(questions)) * 100:.2f}% (Verifier Enforced)")
    print(f"- Engine Counts:             Gemini: {engine_counts['gemini']} | Heuristic Fallback: {engine_counts['heuristic']}")
    print(f"- Fallback Rate:             {fallback_rate:.2f}%")

    # 2. GEMINI-ONLY METRICS
    if gemini_answered_true:
        n_g = len(gemini_answered_true)
        exact_acc_g = sum(1 for t, p in zip(gemini_answered_true, gemini_answered_pred) if t == p) / n_g
        within_1_g = sum(1 for t, p in zip(gemini_answered_true, gemini_answered_pred) if abs(int(t[1]) - int(p[1])) <= 1) / n_g
        kappa_g = compute_cohens_kappa(gemini_answered_true, gemini_answered_pred, categories)

        print(f"\n2. GEMINI-ONLY METRICS (N = {n_g} answered by Gemini):")
        print(f"- Exact-Level Accuracy:      {exact_acc_g * 100:.2f}% ({sum(1 for t, p in zip(gemini_answered_true, gemini_answered_pred) if t == p)}/{n_g})")
        print(f"- Within-One-Level Accuracy: {within_1_g * 100:.2f}%")
        print(f"- Cohen's Kappa (Agreement): {kappa_g:.4f}")

        print_confusion_matrix(gemini_answered_true, gemini_answered_pred, categories)
    else:
        print("\n2. GEMINI-ONLY METRICS: No queries were handled exclusively by Gemini.")

    # 3. HOLD-OUT METRICS (Questions 17-26)
    if holdout_true:
        n_ho = len(holdout_true)
        exact_acc_ho = sum(1 for t, p in zip(holdout_true, holdout_pred) if t == p) / n_ho
        within_1_ho = sum(1 for t, p in zip(holdout_true, holdout_pred) if abs(int(t[1]) - int(p[1])) <= 1) / n_ho
        kappa_ho = compute_cohens_kappa(holdout_true, holdout_pred, categories)

        print(f"\n3. HOLD-OUT EVALUATION METRICS (N = {n_ho} un-tuned hold-out questions):")
        print(f"- Exact-Level Accuracy:      {exact_acc_ho * 100:.2f}% ({sum(1 for t, p in zip(holdout_true, holdout_pred) if t == p)}/{n_ho})")
        print(f"- Within-One-Level Accuracy: {within_1_ho * 100:.2f}%")
        print(f"- Cohen's Kappa (Agreement): {kappa_ho:.4f}")

    print("\n" + "=" * 75)


if __name__ == "__main__":
    run_benchmark()
